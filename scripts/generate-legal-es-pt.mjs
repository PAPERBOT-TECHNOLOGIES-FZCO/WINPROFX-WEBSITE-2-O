function translateValue(value, map, countries) {
  if (typeof value === 'string') {
    if (countries[value]) return countries[value];
    if (map[value]) return map[value];
    return value;
  }
  if (Array.isArray(value)) return value.map((item) => translateValue(item, map, countries));
  if (value && typeof value === 'object') {
    const result = {};
    for (const [k, v] of Object.entries(value)) result[k] = translateValue(v, map, countries);
    return result;
  }
  return value;
}

function writeLocale(locale, map, countries) {
  const translated = translateValue(en, map, countries);
  writeFileSync(join(LOCALES_DIR, locale, 'legal.json'), JSON.stringify(translated, null, 2) + '\n');
  console.log('Wrote', locale + '/legal.json');
}

writeLocale('es', esMap, countryEs);
writeLocale('pt', ptMap, countryPt);

const strings = new Set();
function walk(v) { if (typeof v === 'string') strings.add(v); else if (Array.isArray(v)) v.forEach(walk); else if (v && typeof v === 'object') Object.values(v).forEach(walk); }
walk(en);
const missingEs = [...strings].filter((s) => s && !esMap[s] && !countryEs[s]);
const missingPt = [...strings].filter((s) => s && !ptMap[s] && !countryPt[s]);
if (missingEs.length || missingPt.length) {
  console.error('Missing translations - es:', missingEs.length, 'pt:', missingPt.length);
  if (missingEs.length) console.error(missingEs.join('\n---\n'));
  process.exit(1);
}
